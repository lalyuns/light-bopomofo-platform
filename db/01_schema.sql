-- 輕注音詞庫共享平台：16 張資料表
-- 外鍵沒註明的都是 NO ACTION，效果等同計劃書寫的 RESTRICT（差別只在 NO ACTION 會等到敘述結束才檢查）。
-- 規則檢查（trigger）在 02_triggers.sql，交易函式在 03_functions.sql。

CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- 共用的格式檢查
-- 一個漢字：基本區、擴充 A、相容區、擴充 B 以後
CREATE DOMAIN han_text AS varchar(20)
  CHECK (VALUE ~ '^[\u3400-\u4DBF\u4E00-\u9FFF\uF900-\uFAFF\U00020000-\U000323AF]+$');
-- 完整讀音：音節以空格分隔，例「ㄍㄨㄛˊ ㄌㄩˇ ㄑㄩㄢˋ」
CREATE DOMAIN bopomofo_text AS varchar(100)
  CHECK (VALUE ~ '^[ㄅ-ㄩˊˇˋ˙]+( [ㄅ-ㄩˊˇˋ˙]+)*$');

-- 首字注音：每個音節取第一個符號，「ㄍㄨㄛˊ ㄌㄩˇ ㄑㄩㄢˋ」→「ㄍㄌㄑ」。不存成欄位，用運算式索引。
CREATE FUNCTION initials(bopomofo text) RETURNS text
  LANGUAGE sql IMMUTABLE PARALLEL SAFE
  RETURN regexp_replace(bopomofo, '(\S)\S*\s*', '\1', 'g');

-- 版本號排序：'10.0' → {10,0}，才會排在 '9.0' → {9,0} 後面
CREATE FUNCTION version_key(version text) RETURNS int[]
  LANGUAGE sql IMMUTABLE PARALLEL SAFE
  RETURN string_to_array(version, '.')::int[];


-- ==================== 帳號與裝置 ====================

CREATE TABLE users (
  user_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email         varchar(254) UNIQUE CHECK (email = lower(email)),
  password_hash text NOT NULL,
  display_name  varchar(30) CHECK (char_length(display_name) >= 1),
  role          varchar(10) NOT NULL DEFAULT 'user'   CHECK (role IN ('user', 'editor')),
  status        varchar(10) NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'suspended', 'deleted')),
  created_at    timestamptz NOT NULL DEFAULT now(),
  -- 刪除帳號時才清空 email 與名稱（R1）
  CHECK (status = 'deleted' OR (email IS NOT NULL AND display_name IS NOT NULL))
);

CREATE TABLE devices (
  device_id      uuid PRIMARY KEY,                -- 輸入法產生
  user_id        bigint REFERENCES users,         -- NULL：匿名裝置（R3）
  platform       varchar(10) NOT NULL CHECK (platform IN ('macos', 'windows', 'web')),
  app_version    varchar(20) CHECK (app_version IS NOT NULL OR platform = 'web'),
  first_seen     timestamptz NOT NULL DEFAULT now(),
  last_synced_at timestamptz NOT NULL DEFAULT now(),
  CHECK (last_synced_at >= first_seen)
);
-- 每個帳號最多一台「網頁」裝置
CREATE UNIQUE INDEX devices_one_web_per_user ON devices (user_id) WHERE platform = 'web';


-- ==================== 詞與正式詞庫 ====================

CREATE TABLE sources (
  source_id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name      varchar(50) NOT NULL UNIQUE,
  license   varchar(50),
  url       text,
  version   varchar(20)
);

CREATE TABLE words (
  word_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  text         han_text NOT NULL UNIQUE,          -- 1–20 個漢字（R4）
  corpus_count bigint NOT NULL DEFAULT 0 CHECK (corpus_count >= 0)
);

CREATE TABLE word_pairs (
  word_id      bigint REFERENCES words,           -- 前詞
  next_word_id bigint REFERENCES words,           -- 後詞
  pmi          numeric(3,1) NOT NULL,             -- −99.9 到 99.9
  PRIMARY KEY (word_id, next_word_id)
);

CREATE TABLE lexicon_entries (
  entry_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  word_id     bigint NOT NULL REFERENCES words,
  bopomofo    bopomofo_text NOT NULL,
  frequency   integer NOT NULL CHECK (frequency >= 0),
  source_id   smallint NOT NULL REFERENCES sources,
  -- staged：在草稿版本裡、還沒發布；發布時變 active
  status      varchar(10) NOT NULL DEFAULT 'staged' CHECK (status IN ('staged', 'active', 'retired')),
  updated_by  bigint REFERENCES users,            -- NULL：匯入後沒被編輯改過
  updated_at  timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,         -- 樂觀鎖
  UNIQUE (word_id, bopomofo)                      -- R13
);


-- ==================== 新詞投稿與審核 ====================

CREATE TABLE submissions (
  device_id  uuid   REFERENCES devices,
  word_id    bigint REFERENCES words,
  -- 與輸入法上傳時的檢查相同：只有注音符號與聲調、沒有空格
  typed      varchar(60) CHECK (typed ~ '^[ㄅ-ㄩˉˊˇˋ˙]+$'),
  use_count  integer NOT NULL CHECK (use_count BETWEEN 1 AND 1000000),
  first_seen timestamptz NOT NULL DEFAULT now(),
  last_seen  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (device_id, word_id, typed),        -- R5
  CHECK (last_seen >= first_seen)
);

CREATE TABLE votes (
  user_id  bigint REFERENCES users,
  word_id  bigint REFERENCES words,
  value    smallint NOT NULL CHECK (value IN (1, -1)),
  voted_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, word_id)                  -- 每人每詞一票（R7）
);

CREATE TABLE word_reviews (
  word_id     bigint PRIMARY KEY REFERENCES words,
  status      varchar(10) NOT NULL DEFAULT 'pending'
              CHECK (status IN ('pending', 'approved', 'rejected', 'blocked')),
  reviewer_id bigint REFERENCES users,
  decided_at  timestamptz,
  row_version integer NOT NULL DEFAULT 1,         -- 樂觀鎖（R12）
  -- 待審時沒有決定者與時間，其他狀態兩者都要有
  CHECK ((status = 'pending') = (reviewer_id IS NULL)),
  CHECK ((status = 'pending') = (decided_at IS NULL))
);


-- ==================== 個人詞與詞庫包 ====================

CREATE TABLE personal_words (
  user_id    bigint REFERENCES users,
  word_id    bigint REFERENCES words,
  bopomofo   bopomofo_text,
  status     varchar(10) NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'deleted')),
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, word_id, bopomofo)        -- R19
);

CREATE TABLE packs (
  pack_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        varchar(30) NOT NULL UNIQUE,
  description varchar(200),
  owner_id    bigint NOT NULL REFERENCES users,
  status      varchar(10) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published', 'archived')),
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE pack_entries (
  pack_id  bigint REFERENCES packs ON DELETE CASCADE,
  entry_id bigint REFERENCES lexicon_entries,
  PRIMARY KEY (pack_id, entry_id)
);

CREATE TABLE subscriptions (
  user_id       bigint REFERENCES users,
  pack_id       bigint REFERENCES packs,
  status        varchar(10) NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'cancelled')),
  subscribed_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, pack_id)                  -- 每人每包一筆（R20）
);


-- ==================== 回報與版本 ====================

CREATE TABLE reports (
  report_id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    bigint NOT NULL REFERENCES users,
  entry_id   bigint NOT NULL REFERENCES lexicon_entries,
  kind       varchar(15) NOT NULL CHECK (kind IN ('wrong_reading', 'not_word', 'offensive')),
  note       varchar(200),
  status     varchar(10) NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'resolved', 'dismissed')),
  handler_id bigint REFERENCES users,
  created_at timestamptz NOT NULL DEFAULT now(),
  handled_at timestamptz CHECK (handled_at >= created_at),
  CHECK ((status = 'open') = (handler_id IS NULL)),   -- R17
  CHECK ((status = 'open') = (handled_at IS NULL))
);

CREATE TABLE releases (
  release_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version       varchar(10) NOT NULL UNIQUE CHECK (version ~ '^[0-9]+(\.[0-9]+)*$'),
  status        varchar(10) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published')),
  max_new_words integer NOT NULL DEFAULT 200 CHECK (max_new_words > 0),
  created_by    bigint NOT NULL REFERENCES users,
  published_at  timestamptz,
  note          varchar(500),
  CHECK ((status = 'published') = (published_at IS NOT NULL))
);
-- 同一時間只准一個草稿版本
CREATE UNIQUE INDEX releases_one_draft ON releases (status) WHERE status = 'draft';

CREATE TABLE release_changes (
  release_id    bigint REFERENCES releases ON DELETE CASCADE,
  entry_id      bigint REFERENCES lexicon_entries,
  action        varchar(10) NOT NULL CHECK (action IN ('add', 'remove', 'reweight')),
  old_frequency integer CHECK (old_frequency >= 0),
  new_frequency integer CHECK (new_frequency >= 0),
  PRIMARY KEY (release_id, entry_id),             -- 同一版本對同一詞條只有一筆（R14）
  CHECK (
       (action = 'add'      AND old_frequency IS NULL     AND new_frequency IS NOT NULL)
    OR (action = 'remove'   AND old_frequency IS NOT NULL AND new_frequency IS NULL)
    OR (action = 'reweight' AND old_frequency IS NOT NULL AND new_frequency IS NOT NULL
                            AND old_frequency <> new_frequency))
);


-- ==================== 索引（表三） ====================

-- 完整注音前綴：「ㄍㄨㄛˊ ㄌㄩˇ」開頭的詞條
CREATE INDEX lexicon_entries_bopomofo ON lexicon_entries (bopomofo text_pattern_ops);
-- 首字注音：「ㄍㄌㄑ」
CREATE INDEX lexicon_entries_initials ON lexicon_entries (initials(bopomofo) text_pattern_ops);
-- 詞的一部分：LIKE '%旅券%'
CREATE INDEX words_text_trgm ON words USING gin (text gin_trgm_ops);
-- 某個詞「前面」常接什麼（主鍵只能查後面）
CREATE INDEX word_pairs_next ON word_pairs (next_word_id);
-- 待審列表依詞彙總
CREATE INDEX submissions_word ON submissions (word_id);
CREATE INDEX votes_word ON votes (word_id);
-- 裝置取回「上次同步之後」變動的個人詞
CREATE INDEX personal_words_sync ON personal_words (user_id, updated_at);
-- 同一人對同一詞條的同類回報，同時最多一筆待處理（R18）
CREATE UNIQUE INDEX reports_one_open ON reports (user_id, entry_id, kind) WHERE status = 'open';
